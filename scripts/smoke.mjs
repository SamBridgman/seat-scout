import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { spawn } from 'node:child_process';

await mkdir('docs/screenshots', { recursive: true });
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5174'], { windowsHide: true, stdio: 'pipe' });
await new Promise((resolve, reject) => {
  const timeout = setTimeout(() => reject(new Error('Preview startup timed out')), 15000);
  server.stdout.on('data', data => { if (data.toString().includes('Local:')) { clearTimeout(timeout); resolve(); } });
  server.once('error', reject);
});
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5174');
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('.space-card').count(), 5);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: 'docs/screenshots/desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Seating filter').selectOption('Many seats');
  assert.equal(await page.locator('.space-card').count(), 2);
  await page.getByLabel('Atmosphere filter').selectOption('Quiet');
  await page.getByText('No spaces match just yet.').waitFor();
  await page.getByRole('button', { name: 'Clear search & filters' }).click();
  await page.getByPlaceholder('Search a library, lounge, or study space').fill('stone');
  assert.equal(await page.locator('.space-card').count(), 1);
  await page.getByRole('button', { name: /View Stone Science Library/ }).click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.getByRole('dialog').getByText('Unknown', { exact: true }).count(), 2);
  await page.getByRole('button', { name: 'Report conditions' }).click();
  assert.equal(await page.getByRole('button', { name: 'Submit report' }).isDisabled(), true);
  await page.getByRole('button', { name: /Many seats Plenty/ }).click();
  await page.getByRole('button', { name: /Quiet Little/ }).click();
  await page.screenshot({ path: 'docs/screenshots/report.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Submit report' }).click();
  await page.getByRole('status').filter({hasText:'Report added'}).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /My reports/ }).click();
  assert.equal(await page.locator('.reports-list article').count(), 1);
  await page.getByRole('button', { name: 'Find a space' }).click();
  await page.getByRole('button', { name: 'Map', exact: true }).click();
  assert.equal(await page.locator('.map-pin').count(), 5);
  await page.screenshot({ path: 'docs/screenshots/map.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'View Mugar Memorial Library', exact: true }).click();
  const directions=page.getByRole('link',{name:/Directions/});
  assert.match(await directions.getAttribute('href'), /^https:\/\/www.google.com\/maps\/search/);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('button', { name: 'Grid', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: 'docs/screenshots/mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'How it works', exact: true }).click();
  await page.getByText('Conditions change. We show the uncertainty.').waitFor();
  await page.getByRole('button', { name: 'Find your next spot' }).click();
  await page.getByRole('button', { name: /View Mugar Memorial Library/ }).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: 'docs/screenshots/mobile-detail.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Close dialog' }).focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.getByRole('link',{name:/Directions/}).evaluate(el=>el===document.activeElement),true);
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button',{name:'Close dialog'}).evaluate(el=>el===document.activeElement),true);
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('PASS: desktop and mobile; filters; empty state; unknown data; report validation and persistence; map; directions; keyboard dialog controls; no page errors.');
} finally { await browser.close(); server.kill(); }

