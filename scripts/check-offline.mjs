import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const target = resolve(process.argv[2] || 'Seat-Scout.html');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, offline: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(target).href);
  await page.waitForTimeout(500);
  assert.match(await page.title(), /Seat-Scout/);
  assert.equal(await page.locator('.space-card').count(), 5, 'Opening the HTML directly must render five spaces without a server');
  await page.getByLabel('Search study spaces').fill('stone');
  await expect(page.locator('.space-card')).toHaveCount(1);
  await page.getByLabel('Clear search').click();
  await page.getByLabel('Seating filter').selectOption('Many seats');
  await expect(page.locator('.space-card')).toHaveCount(2);
  await page.getByLabel('Atmosphere filter').selectOption('Quiet');
  await expect(page.getByText('No spaces match just yet.')).toBeVisible();
  await page.getByRole('button', { name: 'Clear search & filters' }).click();
  await page.getByRole('button', { name: /View Stone Science Library/ }).click();
  await expect(page.getByRole('dialog').getByText('Unknown', { exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Report conditions' }).click();
  await expect(page.getByRole('button', { name: 'Submit report' })).toBeDisabled();
  await page.getByRole('button', { name: /Many seats Plenty/ }).click();
  await page.getByRole('button', { name: /Quiet Little/ }).click();
  await page.getByRole('button', { name: 'Submit report' }).click();
  await page.getByRole('status').filter({ hasText: 'Report added' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /My reports/ }).click();
  await expect(page.locator('.reports-list article')).toHaveCount(1);
  await page.getByRole('button', { name: 'Find a space' }).click();
  await page.getByRole('button', { name: /View Stone Science Library/ }).click();
  await expect(page.getByRole('dialog').locator('.panel-values')).toContainText('Many seats');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Map', exact: true }).click();
  assert.equal(await page.locator('.map-pin').count(), 5);
  await page.getByRole('button', { name: 'View Mugar Memorial Library', exact: true }).click();
  assert.match(await page.getByRole('link', { name: /Directions/ }).getAttribute('href'), /^https:\/\/www.google.com\/maps\/search/);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Grid', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'How it works', exact: true }).click();
  await expect(page.getByText('Conditions change. We show the uncertainty.')).toBeVisible();
  await page.getByRole('button', { name: 'Find your next spot' }).click();
  await page.getByRole('button', { name: /View Stone Science Library/ }).click();
  await page.getByRole('button', { name: 'Close dialog' }).focus();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('link', { name: /Directions/ })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'Close dialog' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const restricted = await browser.newPage({ offline: true });
  restricted.on('pageerror', error => errors.push(error.message));
  await restricted.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Storage blocked', 'SecurityError'); } }));
  await restricted.goto(pathToFileURL(target).href);
  await expect(restricted.locator('.space-card')).toHaveCount(5);
  await restricted.getByRole('button', { name: /View Stone Science Library/ }).click();
  await restricted.getByRole('button', { name: 'Report conditions' }).click();
  await restricted.getByRole('button', { name: /Many seats Plenty/ }).click();
  await restricted.getByRole('button', { name: /Quiet Little/ }).click();
  await restricted.getByRole('button', { name: 'Submit report' }).click();
  await expect(restricted.locator('.storage-notice')).toContainText('last for this session');
  await restricted.close();
  assert.deepEqual(errors, []);
  console.log('PASS: extracted HTML works offline; branding, search, filters, empty state, unknown conditions, report validation and persistence, map pins, directions URL, mobile navigation, keyboard focus, and blocked-storage fallback. No JavaScript errors.');
} finally { await browser.close(); }
