// Runs the team's reports schema and the ML migrations in an in-memory
// Postgres (PGlite) and checks that:
//   1. estimate_conditions() matches the Python reference model,
//   2. app upserts to reports are copied into report_events, including under RLS,
//   3. the trigger never blocks a write to reports,
//   4. clients can call the function but cannot read raw history,
//   5. both migrations can run twice.
// Run from ml/:  npm install && node tests/sql_parity.mjs

import { PGlite } from "@electric-sql/pglite";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reportsSql = join(root, "..", "android", "supabase", "reports.sql");
const reportsCsv = join(root, "data", "synthetic_reports.csv");
if (!existsSync(reportsCsv)) execFileSync("python3", [join(root, "synthetic.py")], { stdio: "inherit" });

let failures = 0;
const check = (ok, message) => {
  console.log(`${ok ? "PASS" : "FAIL"}  ${message}`);
  if (!ok) failures++;
};

function readCsv(path) {
  const [header, ...lines] = readFileSync(path, "utf8").trim().split(/\r?\n/);
  const cols = header.split(",");
  return lines.map((line) => {
    const values = line.match(/("([^"]|"")*"|[^,]*)(,|$)/g)
      .map((v) => v.replace(/,$/, "").replace(/^"|"$/g, "").replace(/""/g, '"'));
    return Object.fromEntries(cols.map((c, i) => [c, values[i]]));
  });
}
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const db = new PGlite();
const areas = readCsv(join(root, "data", "areas.csv"));

// Stand-ins for Supabase: roles, auth.users, auth.uid() and the study_area table.
await db.exec(`
  create role anon; create role authenticated;
  create schema auth;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema auth to anon, authenticated;
  grant execute on function auth.uid() to anon, authenticated;
  create table public.study_area (id bigint generated by default as identity primary key,
    name text, building text, zone text);
  grant select on public.study_area to anon, authenticated;
  insert into public.study_area (id, name, building, zone) values
    ${areas.map((a) => `(${a.area_id}, ${q(a.name)}, ${q(a.building)}, ${q(a.zone)})`).join(",")};
`);
await db.exec(readFileSync(reportsSql, "utf8"));

const m1 = readFileSync(join(root, "sql", "001_report_history.sql"), "utf8");
const m2 = readFileSync(join(root, "sql", "002_estimate_conditions.sql"), "utf8");
for (let i = 0; i < 2; i++) {
  await db.exec(m1);
  await db.exec(m2);
}
check(true, "android/supabase/reports.sql, then both ML migrations twice, run without error");

// Load synthetic history straight into report_events with its original times.
const reports = readCsv(reportsCsv);
await db.exec(`insert into report_events (area_id, seats, atmosphere, reported_at) values ${reports
  .map((r) => `(${r.area_id}, ${q(r.seats)}, ${q(r.atmosphere)}, ${q(r.reported_at)})`)
  .join(",")};`);

const last = reports[reports.length - 1].reported_at;
const times = [
  last, // live reports present
  new Date(Date.parse(last) + 10 * 60_000).toISOString(),
  "2026-11-18T20:00:00Z", // Wednesday 15:00 Boston
  "2026-11-14T17:00:00Z", // Saturday 12:00 Boston
  "2026-10-27T13:30:00Z", // Tuesday 09:30 Boston, during EDT
  "2026-10-09T02:00:00Z", // Thursday 22:00 Boston, near the start of the data
];
const expected = JSON.parse(execFileSync("python3",
  [join(root, "tests", "parity_expected.py"), reportsCsv, ...times], { encoding: "utf8" }));

let compared = 0;
let worst = 0;
const mismatches = [];
const bases = new Set();
for (const t of times) {
  const { rows } = await db.query("select * from estimate_conditions($1)", [t]);
  const want = expected[t];
  if (rows.length !== want.length) {
    mismatches.push(`${t}: ${rows.length} rows from SQL, ${want.length} from Python`);
    continue;
  }
  rows.forEach((got, i) => {
    const w = want[i];
    bases.add(got.basis);
    const diffs = [
      Math.abs(got.probability - w.probability),
      Math.abs(got.history_weight - w.history_weight),
      ...Object.keys(w.probabilities).map((k) => Math.abs(Number(got.probabilities[k]) - w.probabilities[k])),
    ];
    worst = Math.max(worst, ...diffs);
    const same = got.area_id === String(w.area_id) && got.dimension === w.dimension &&
      got.label === w.label && got.basis === w.basis && got.history_reports === w.history_reports &&
      got.live_reports === w.live_reports && Math.max(...diffs) < 2e-4;
    if (!same) mismatches.push(`${t} ${w.area_id} ${w.dimension}: SQL ${JSON.stringify(got)} vs Python ${JSON.stringify(w)}`);
    compared++;
  });
}
check(mismatches.length === 0,
  `SQL matches Python on ${compared} estimates at ${times.length} times (max difference ${worst.toExponential(1)})`);
mismatches.slice(0, 5).forEach((m) => console.log("      " + m));
check(bases.has("live") && bases.has("pattern") && bases.has("insufficient"),
  `test times cover every basis (${[...bases].join(", ")})`);

// Trigger behaviour. These events get now() as their time, after all test times above.
const user = "00000000-0000-4000-8000-000000000001";
await db.exec(`insert into auth.users values ('${user}')`);
const count = async () => (await db.query("select count(*)::int as n from report_events")).rows[0].n;
const before = await count();

// The app's exact write: an upsert on (user_id, area_id) as an authenticated user under RLS.
await db.exec(`set role authenticated; set request.jwt.claim.sub = '${user}';`);
const upsert = (area, seats, atmosphere) => db.query(
  `insert into reports (user_id, area_id, seats, atmosphere) values ($1, $2, $3, $4)
   on conflict (user_id, area_id) do update set seats = excluded.seats, atmosphere = excluded.atmosphere
   returning area_id, seats, atmosphere, saved_at`, [user, area, seats, atmosphere]);
const first = await upsert("2", "MANY", "QUIET");
await upsert("2", "FEW", "MODERATE");
await upsert("1", "FULL", "NOISY");
await db.exec("reset role; reset request.jwt.claim.sub;");
check(first.rows.length === 1 && first.rows[0].saved_at > 0, "the app's upsert still returns its row with saved_at");
check((await count()) === before + 3, "authenticated upserts are all kept in history, including replaced reports");
const latest = await db.query(
  "select area_id::int, seats, atmosphere, reporter::text from report_events order by id desc limit 3");
check(JSON.stringify(latest.rows) === JSON.stringify([
  { area_id: 1, seats: "FULL", atmosphere: "NOISY", reporter: user },
  { area_id: 2, seats: "FEW", atmosphere: "MODERATE", reporter: user },
  { area_id: 2, seats: "MANY", atmosphere: "QUIET", reporter: user },
]), "history rows carry the area, values and reporter");
const current = await db.query("select count(*)::int as n from reports where user_id = $1", [user]);
check(current.rows[0].n === 2, "reports still keeps one current row per user and area");

// Rows the policies would reject for clients, inserted as the owner, must still save.
await db.exec(`insert into reports (user_id, area_id, seats, atmosphere) values
  ('${user}', '999', 'FEW', 'QUIET'), ('${user}', 'mugar4', 'FEW', 'QUIET')`);
check((await count()) === before + 3, "reports for unknown or non-numeric areas save but are skipped in history");

// Client permissions.
for (const role of ["anon", "authenticated"]) {
  await db.exec(`set role ${role}`);
  let blocked = false;
  try {
    await db.query("select * from report_events limit 1");
  } catch {
    blocked = true;
  }
  const rows = await db.query("select count(*)::int as n from estimate_conditions()");
  await db.exec("reset role");
  check(blocked && rows.rows[0].n === areas.length * 2,
    `${role} cannot read raw history but can call estimate_conditions()`);
}

await db.close();
console.log(failures ? `\n${failures} check(s) failed` : "\nAll SQL checks passed");
process.exit(failures ? 1 : 0);
